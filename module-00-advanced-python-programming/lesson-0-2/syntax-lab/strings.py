# Single and double quotes
print('print("hello")')
print("It's 10 seconds")

# Escapes: \t is a tab and \n starts a new line
print("Name:\tsyntax-lab\nPython:\t3.13")

# Length
word = "syntax"
print(len(word))
print(len("a\tb"))

# Indexing
print(word[0], word[1], word[5])
print(word[-1], word[-2])

# Slicing
print(word[0:3], word[1:4])
print(word[:3], word[3:], word[-3:])
